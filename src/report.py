"""Write results/summary.md and copy it into README.md between the RESULTS markers."""
from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import pandas as pd

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def md_table(df: pd.DataFrame, fmt: str = "{:.2f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = ["-" if isinstance(v, (float, np.floating)) and np.isnan(v)
                 else fmt.format(v) if isinstance(v, (float, np.floating)) else str(v) for v in r.values]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _iqr(x: pd.Series) -> str:
    return f"{x.median():.3f} ({x.quantile(.25):.3f} to {x.quantile(.75):.3f})"


def build_summary(real: dict | None, phys: dict) -> str:
    out = [f"_Generated by `run_eda.py` on {time.strftime('%Y-%m-%d')}._", ""]
    if real:
        df = real["df"]
        rest, stress = df[df.condition == "Rest"], df[df.condition == "Stress"]
        out += ["**Real data**", "",
                f"- {len(df)} slice series from {df.patient.nunique()} patients "
                f"({len(rest)} rest, {len(stress)} stress); time axis in "
                f"{'seconds' if (df.time_unit == 's').all() else 'frames'}.",
                f"- Upslope ratio, median (IQR): rest {_iqr(rest.upslope_ratio)}, stress {_iqr(stress.upslope_ratio)}.",
                f"- Peak-to-peak breathing motion of the LV: median {df.motion_p2p_mm.median():.1f} mm "
                f"(max {df.motion_p2p_mm.max():.1f} mm).",
                f"- Myocardial contrast-to-noise ratio: median {df.cnr_myo.median():.1f}."]
        mpri = real["mpri"]
        if len(mpri):
            out.append(f"- Perfusion reserve index (stress / rest upslope ratio): median {mpri.MPRI.median():.2f}; "
                       f"{int((mpri.MPRI < 1.5).sum())} of {len(mpri)} patients below 1.5.")
        dd = (real["dose"].groupby("dose_fraction")[["whole_slice_rel_sd", "sector_rel_sd"]].median()
              .sort_index(ascending=False).reset_index())
        dd.columns = ["dose fraction", "whole-slice variability", "single-sector variability"]
        out += ["", "Simulated dose reduction on the real curves "
                "(relative SD of the upslope ratio, median over series):", "", md_table(dd), ""]
    fits = phys["fits"]
    t = (fits.assign(err=lambda d: (d.Fp_est - d.Fp_true).abs() / d.Fp_true)
         .groupby(["dose", "tissue"]).err.median().unstack().sort_index(ascending=False).reset_index())
    t.columns = ["dose", *[f"median abs. Fp error, {c}" for c in t.columns[1:]]]
    cal = (phys["calibration"].pivot(index="dose", columns="source", values="coverage_95")
           .sort_index(ascending=False).reset_index())
    cal.columns = ["dose", *[f"95% interval coverage, {c}" for c in cal.columns[1:]]]
    out += ["**Physics simulation (2CXM, SNR 17.5 at full dose)**", "", md_table(t), "", md_table(cal), ""]
    return "\n".join(out)


def write_summary(text: str, results_dir: Path) -> None:
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "summary.md").write_text(text, encoding="utf-8")


def update_readme(text: str, readme: Path, log=print) -> None:
    """Replace only the text between the RESULTS markers; leave everything else untouched."""
    if not readme.exists():
        return
    s = readme.read_text(encoding="utf-8")
    if START not in s or END not in s:
        log("  README.md has no RESULTS markers - not modified")
        return
    head, rest = s.split(START, 1)
    _, tail = rest.split(END, 1)
    readme.write_text(head + START + "\n" + text + "\n" + END + tail, encoding="utf-8")
    log("  README.md results section updated")
